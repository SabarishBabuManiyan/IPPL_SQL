FROM dbo.[Object] o WHERE o.[Type] = 1  -- NAV Object Type = Table (change if your DB uses different value)
), FMap AS ( SELECT nm.[TableNo], nm.[FieldNo], nm.[FieldName],  ROW_NUMBER() OVER (PARTITION BY nm.[TableNo], nm.[FieldNo]
 ORDER BY nm.[FieldName]
) AS rn
FROM #NAV_Field_Map nm
)
SELECT
x.COMPANY,
x.[Entry No_]  AS [Entry No_],
x.[Date and Time] AS [Date and Time],
x.[User ID] AS [User ID],
x.[Table No_] AS [Table No_],
o.[Name]  AS [Table Name],
x.[Field No_] AS [Field No_],
fm.[FieldName] AS [Field Name],
x.[Type of Change]  AS [Type of Change],
CASE
    WHEN x.[Type of Change] = 0 THEN 'Insertion'
    WHEN x.[Type of Change] = 1 THEN 'Modification'
    ELSE 'Deletion'
END  AS [type_of_Change],
x.[Old Value]   AS [Old Value],
x.[New Value]  AS [New Value],
x.[Primary Key]  AS [Primary Key],
x.[Primary Key Field 1 No_]  AS [Primary Key Field 1 No_],
